# Regenerates index.tsx from the episode files present: <Name>.tsx exports Ml<Name>, timeline ml-<name lower>.json.
import os
here = os.path.dirname(os.path.abspath(__file__))
names = sorted(f[:-4] for f in os.listdir(here) if f.endswith('.tsx') and f not in ('kit.tsx', 'index.tsx'))
imp = '\n'.join(f"import {{ Ml{n} }} from './{n}';\nimport t{n} from '../timelines/ml-{n.lower()}.json';" for n in names)
comps = '\n'.join(f"  {{comp('Ml{n}', Ml{n}, t{n})}}" for n in names)
open(os.path.join(here, 'index.tsx'), 'w').write(f"""// COE305 compositions (registered in ../Root.tsx). Generated by gen_index.py; narration in ../../scripts/coe305.py.
import React from 'react';
import {{ Composition }} from 'remotion';
import {{ makeTL }} from '../lib';
{imp}

const comp = (id: string, component: React.FC, t: unknown) => {{
  const {{ TL }} = makeTL(t);
  return <Composition key={{id}} id={{id}} component={{component}} durationInFrames={{TL.total}} fps={{TL.fps}} width={{1920}} height={{1080}} />;
}};

export const MlComps: React.FC = () => <>
{comps}
</>;
""")
print(names)
